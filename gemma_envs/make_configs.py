#!/usr/bin/env python3
"""sweep/mission_gemma_envs.md: rh-envs configs configs/<env>/gemma4_31b_on.yaml for the screened envs = the Qwen config the round-2 pilots used,
with only the thinking kwargs (enable_thinking true, vLLM thinking_token_budget 4096) and the per-call max_tokens (8192) changed; every other
line (sampling, env settings, comments) kept. Usage: make_configs.py <rh-envs configs dir> <env>:<qwen config>[:<out name>] ..."""
import re, sys
from pathlib import Path

HEADER = "# google/gemma-4-31B-it, thinking on (sweep/mission_gemma_envs.md): {src} with only the thinking kwargs (enable_thinking true; vLLM thinking_token_budget 4096)\n# and the per-call max_tokens (8192) changed. Generated by ortho gemma_envs/make_configs.py.\n"

def convert(text: str) -> str:
    assert text.count("reasoning_effort: low") == 1, "expected exactly one reasoning_effort: low"
    m = re.search(r"^(\s*)chat_template_kwargs:\n(\s*)reasoning_effort: low\n", text, re.M)
    assert m, "chat_template_kwargs block not found"
    ind = m.group(1)
    text = text.replace(m.group(0), f"{ind}thinking_token_budget: 4096\n{ind}chat_template_kwargs:\n{m.group(2)}enable_thinking: true\n")
    model = text.index("\nmodel:")
    head, tail = text[:model], text[model:]
    assert len(re.findall(r"^\s+max_tokens: \d+", tail, re.M)) == 1, "expected one max_tokens in the model block"
    tail = re.sub(r"^(\s+)max_tokens: \d+", r"\1max_tokens: 8192", tail, flags=re.M)
    return head + tail

root = Path(sys.argv[1])
for spec in sys.argv[2:]:
    env, src, *out = spec.split(":")
    out = out[0] if out else "gemma4_31b_on"
    text = (root / env / f"{src}.yaml").read_text()
    new = HEADER.format(src=f"{src}.yaml") + convert(text)
    (root / env / f"{out}.yaml").write_text(new)
    print(f"{env}/{out}.yaml from {src}.yaml")
