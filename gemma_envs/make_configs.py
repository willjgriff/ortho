#!/usr/bin/env python3
"""rh-envs configs configs/<env>/<tag>_on.yaml for a model = the Qwen config the round-2 pilots used, with only the thinking kwargs and the per-call
max_tokens (8192) changed; every other line (sampling, env settings, comments) kept. sweep/mission_gemma_envs.md (Gemma, --think budget) and
sweep/mission_model_pilots.md (the model is a parameter).
  --think budget: enable_thinking true and vLLM thinking_token_budget 4096 (Gemma 4, Nanbeige4.3)
  --think effort: the Qwen config's chat-template reasoning_effort low kept as it is (K2 Horizon: low is its lowest level)
Usage: make_configs.py [--tag gemma4_31b] [--think budget|effort] [--model <hf id>] <rh-envs configs dir> <env>:<qwen config>[:<out name>] ..."""
import argparse, re
from pathlib import Path

HEADER = {"budget": "# {model}, thinking on ({mission}): {src} with only the thinking kwargs (enable_thinking true; vLLM thinking_token_budget 4096)\n# and the per-call max_tokens (8192) changed. Generated by ortho gemma_envs/make_configs.py.\n",
          "effort": "# {model}, reasoning_effort low ({mission}): {src} with only the per-call max_tokens (8192) changed; its chat-template reasoning_effort low\n# is kept (the model's lowest level). Generated by ortho gemma_envs/make_configs.py --think effort.\n"}

def convert(text: str, think: str) -> str:
    assert text.count("reasoning_effort: low") == 1, "expected exactly one reasoning_effort: low"
    m = re.search(r"^(\s*)chat_template_kwargs:\n(\s*)reasoning_effort: low\n", text, re.M)
    assert m, "chat_template_kwargs block not found"
    if think == "budget":
        ind = m.group(1)
        text = text.replace(m.group(0), f"{ind}thinking_token_budget: 4096\n{ind}chat_template_kwargs:\n{m.group(2)}enable_thinking: true\n")
    model = text.index("\nmodel:")
    head, tail = text[:model], text[model:]
    assert len(re.findall(r"^\s+max_tokens: \d+", tail, re.M)) == 1, "expected one max_tokens in the model block"
    tail = re.sub(r"^(\s+)max_tokens: \d+", r"\1max_tokens: 8192", tail, flags=re.M)
    return head + tail

ap = argparse.ArgumentParser()
ap.add_argument("--tag", default="gemma4_31b"); ap.add_argument("--think", default="budget", choices=("budget", "effort"))
ap.add_argument("--model", default="google/gemma-4-31B-it"); ap.add_argument("--mission", default="sweep/mission_gemma_envs.md")
ap.add_argument("root"); ap.add_argument("specs", nargs="+")
a = ap.parse_args()
root = Path(a.root)
for spec in a.specs:
    env, src, *out = spec.split(":")
    out = out[0].replace("{tag}", a.tag) if out else f"{a.tag}_on"
    text = (root / env / f"{src}.yaml").read_text()
    new = HEADER[a.think].format(src=f"{src}.yaml", model=a.model, mission=a.mission) + convert(text, a.think)
    (root / env / f"{out}.yaml").write_text(new)
    print(f"{env}/{out}.yaml from {src}.yaml")
